import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:5173');
await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
await page.getByRole('button',{name:'Book Project deposit'}).click();
await page.getByText('Booking will open once', {exact:false}).waitFor();
await page.getByRole('button',{name:'Close checkout'}).click();
await page.getByLabel('Your name').fill('Test Homeowner');
await page.getByLabel('Email address').fill('test@example.com');
await page.getByLabel('Phone number').fill('5125550100');
await page.getByLabel('ZIP code').fill('78701');
await page.getByRole('checkbox').check();
await page.getByRole('button',{name:'Request my estimate'}).click();
await page.getByRole('status').filter({hasText:'could not be sent'}).waitFor();
await page.setViewportSize({width:390,height:844});
await page.goto('http://localhost:5173');
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile overflow');
await page.screenshot({path:'artifacts/mobile.png',fullPage:true});
assert.deepEqual(errors,[]);
console.log('PASS: desktop render, checkout unavailable state, form unavailable state, mobile overflow, no runtime errors. Real Whop API checks NOT run.');
await browser.close();
